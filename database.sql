-- Create database
CREATE DATABASE IF NOT EXISTS votaciones;

USE votaciones;

-- Create table for authorized cedulas
CREATE TABLE IF NOT EXISTS cedulas_autorizadas (
    id INT AUTO_INCREMENT PRIMARY KEY,
    cedula VARCHAR(20) NOT NULL UNIQUE,
    nombre VARCHAR(100) NOT NULL,
    activa BOOLEAN DEFAULT TRUE
);

-- Create table for votes
CREATE TABLE IF NOT EXISTS votos (
    id INT AUTO_INCREMENT PRIMARY KEY,
    cedula_id INT NOT NULL,
    voto VARCHAR(50) NOT NULL,
    fecha_voto TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (cedula_id) REFERENCES cedulas_autorizadas(id)
);

